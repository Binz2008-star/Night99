	UDim = UDim.new,
	UDim2 = UDim2.new,
	Vector2 = Vector2.new,
	Vector3 = Vector3.new,
	Color3 = Color3.new,
	NumberSequence = NumberSequence.new,
	NumberSequenceKeypoint = NumberSequenceKeypoint.new,
