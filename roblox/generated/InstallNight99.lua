-- Returns the child, creating it if needed. Second result is true when created.
local function ensure(parent, name, className)
	local existing = parent:FindFirstChild(name)
	if existing and existing.ClassName ~= className then
		existing:Destroy()
		existing = nil
	end
	if existing then
		return existing, false
	end
	local created = Instance.new(className)
	created.Name = name
	created.Parent = parent
	return created, true
end

local createdCount, updatedCount = 0, 0

for _, entry in ipairs(SOURCES) do
	local parts = entry.path
	local node = game:GetService(parts[1])

	-- Everything between the service and the script is a plain Folder.
	for i = 2, #parts - 1 do
		node = ensure(node, parts[i], "Folder")
	end

	local leaf, isNew = ensure(node, parts[#parts], entry.className)

	if leaf.Source ~= entry.source then
		leaf.Source = entry.source
		-- Plain Lua, no += : this file is parsed as 5.1 by check-install.mjs so the
		-- embedded sources can be diffed instead of trusted.
		if isNew then
			createdCount = createdCount + 1
		else
			updatedCount = updatedCount + 1
		end
	end
end

