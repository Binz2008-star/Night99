local function showBanner(text, duration)
	elements.banner.Text = text
	elements.banner.TextTransparency = 0
	TweenService:Create(
		elements.banner,
		TweenInfo.new(duration, Enum.EasingStyle.Sine, Enum.EasingDirection.InOut),
		{ TextTransparency = 1 }
	):Play()
end

local function showFlash(color, peak)
	elements.flash.BackgroundColor3 = color
	elements.flash.BackgroundTransparency = 1
	TweenService:Create(
		elements.flash,
		TweenInfo.new(0.12),
		{ BackgroundTransparency = peak }
	):Play()
	TweenService:Create(
		elements.flash,
		TweenInfo.new(0.5, Enum.EasingStyle.Quad),
		{ BackgroundTransparency = 1 }
	):Play()
end

function HUD.Init(net, monsterClient)
	build()

	-- Touch devices get the button instead of the keyboard hint.
	local isTouch = UserInputService.TouchEnabled
		or (UserInputService.GamepadEnabled and not UserInputService.KeyboardEnabled)
	elements.toggleButton.Visible = isTouch
	elements.hint.Text = isTouch and "tap LIGHT" or "F  flashlight"

	net.State.OnClientEvent:Connect(function(state)
		local fraction = math.clamp(state.battery / state.maxBattery, 0, 1)

		elements.batteryFill.Size = UDim2.fromScale(math.max(fraction, 0.001), 1)
		elements.batteryText.Text = string.format("BATTERY %d%%", math.round(state.battery))

		-- Below the repel threshold the light stops protecting you, so say so.
		local repelling = state.lightOn and fraction > Config.Monster.RepelBatteryFactor
		if not repelling and fraction <= Config.Monster.RepelBatteryFactor then
			elements.batteryFill.BackgroundColor3 = COLORS.warn
			elements.batteryText.TextColor3 = COLORS.warn
			elements.batteryText.Text = string.format("BATTERY %d%%  LOW", math.round(state.battery))
		elseif state.lightOn then
			elements.batteryFill.BackgroundColor3 = COLORS.amber
			elements.batteryText.TextColor3 = COLORS.ink
		else
			elements.batteryFill.BackgroundColor3 = COLORS.dim
			elements.batteryText.TextColor3 = COLORS.dim
		end

		elements.nightTitle.Text = string.format("NIGHT %d", state.night)
		elements.bestNight.Text = string.format("BEST %d", state.bestNight)
		elements.toggleButton.Text = state.lightOn and "ON" or "LIGHT"
		elements.toggleButton.TextColor3 = state.lightOn and COLORS.amber or COLORS.dim
	end)

	net.GameEvent.OnClientEvent:Connect(function(name, payload)
		if name == "NightStarted" then
			showBanner(string.format("NIGHT %d", payload.night), 4)
		elseif name == "NightEnded" then
			showBanner("THE FOREST IS QUIET", 3)
		elseif name == "BatteryPickup" then
			showBanner(string.format("+%d BATTERY", payload), 1.2)
		elseif name == "BatteryDepleted" then
			showBanner("BATTERY DEAD", 2)
		elseif name == "Hit" then
			showFlash(COLORS.danger, 0.55)
		elseif name == "Died" then
			showFlash(Color3.fromRGB(10, 0, 0), 0.9)
			showBanner(string.format("%s FOUND YOU", Config.Game.MonsterName), 6)
		end
	end)

	-- Proximity vignette, driven by the last known monster position.
	task.spawn(function()
		while screen and screen.Parent do
			local proximity = monsterClient.Proximity()
			-- TODO(audio): drive a heartbeat loop whose rate follows `proximity`.
			-- The client is only guessing, so keep it subtle and rhythmic.
			local pulse = 0.5 + 0.5 * math.sin(os.clock() * (4 + proximity * 9))
			elements.vignette.BackgroundTransparency = 1 - (proximity * pulse * 0.75)
			elements.vignette.Size = UDim2.fromScale(1 + proximity * 0.15, 1 + proximity * 0.15)
			elements.vignette.Position = UDim2.fromOffset(
				-screen.AbsoluteSize.X * proximity * 0.075,
				-screen.AbsoluteSize.Y * proximity * 0.075
			)
			task.wait(0.05)
		end
	end)
end

return HUD]==],
